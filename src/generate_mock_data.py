def build_dataframe(players_list):
    rows = []
    for p in players_list:
        name, team, pos, gp, pts, ast, reb, stl, blk, fg_pct, fg3_pct, ft_pct, tov, pm, usg = p

        # Добавляем небольшой шум
        noise = lambda v, s: max(0, round(v + np.random.normal(0, s), 3))

        rows.append({
            "PLAYER_NAME": name,
            "TEAM_ABBREVIATION": team,
            "PLAYER_POSITION": pos,
            "GP": gp,
            "PTS": noise(pts, 0.5),
            "AST": noise(ast, 0.2),
            "REB": noise(reb, 0.3),
            "STL": noise(stl, 0.05),
            "BLK": noise(blk, 0.05),
            "FG_PCT": round(min(0.85, noise(fg_pct, 0.01)), 3),
            "FG3_PCT": round(min(0.55, noise(fg3_pct, 0.01)), 3) if fg3_pct > 0.01 else 0.0,
            "FT_PCT": round(min(0.99, noise(ft_pct, 0.01)), 3),
            "TOV": noise(tov, 0.2),
            "PLUS_MINUS": round(pm + np.random.normal(0, 0.5), 1),
            "USG_PCT": round(min(0.45, noise(usg, 0.005)), 3),
            "TS_PCT": round(min(0.85, noise(fg_pct * 1.05, 0.01)), 3),
        })
    return pd.DataFrame(rows)


